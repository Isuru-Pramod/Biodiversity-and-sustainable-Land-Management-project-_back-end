const { sql, poolPromise } = require('../db');
const testCatalog = require('../data/testFieldCatalog.json');

const activeTable = 'dbo.TeaFarmer_Records';
const testBackupTable = 'dbo.TeaFarmer_Records_TestBackup';
const actualBackupTable = 'dbo.TeaFarmer_Records_Actual_Backup';

function quoteIdentifier(identifier) {
  return '[' + identifier.replaceAll(']', ']]') + ']';
}

async function main() {
  const pool = await poolPromise;
  const stateResult = await pool.request().query(
    "SELECT OBJECT_ID(N'" + activeTable + "', N'U') AS activeTable, " +
    "OBJECT_ID(N'" + testBackupTable + "', N'U') AS testBackupTable, " +
    "OBJECT_ID(N'" + actualBackupTable + "', N'U') AS actualBackupTable"
  );
  const state = stateResult.recordset[0];

  if (!state.activeTable || !state.testBackupTable) {
    throw new Error('Expected both the active actual table and retained test table before restoring.');
  }
  if (state.actualBackupTable) {
    throw new Error(actualBackupTable + ' already exists. Nothing was changed.');
  }

  const testSchemaResult = await pool.request()
    .input('idColumn', sql.NVarChar(128), testCatalog.recordIdColumn)
    .query(
      'SELECT COUNT_BIG(*) AS [columnCount], ' +
      'MAX(CASE WHEN [name] = @idColumn THEN 1 ELSE 0 END) AS [recordIdColumnExists], ' +
      'SUM(CASE WHEN [name] = @idColumn AND [is_identity] = 1 THEN 1 ELSE 0 END) AS [identityColumn] ' +
      'FROM sys.columns WHERE [object_id] = OBJECT_ID(N\'' + testBackupTable + '\', N\'U\')'
    );
  const testSchema = testSchemaResult.recordset[0];
  if (Number(testSchema.columnCount) !== testCatalog.sourceFieldCount) {
    throw new Error('The saved test table has ' + testSchema.columnCount + ' columns; expected ' + testCatalog.sourceFieldCount + '. Nothing was changed.');
  }
  if (Number(testSchema.recordIdColumnExists) !== 1) {
    throw new Error('The saved test table does not contain its Record ID field. Nothing was changed.');
  }

  const idColumn = quoteIdentifier(testCatalog.recordIdColumn);
  const idValidation = await pool.request().query(
    'SELECT COUNT_BIG(*) AS [rowCount], ' +
    'SUM(CASE WHEN TRY_CONVERT(BIGINT, ' + idColumn + ') IS NULL THEN 1 ELSE 0 END) AS [invalidIds], ' +
    'COUNT(DISTINCT TRY_CONVERT(BIGINT, ' + idColumn + ')) AS [uniqueIds] ' +
    'FROM ' + testBackupTable
  );
  const idTotals = idValidation.recordset[0];
  if (Number(idTotals.invalidIds) !== 0 || Number(idTotals.uniqueIds) !== Number(idTotals.rowCount)) {
    throw new Error('The saved test table contains missing, nonnumeric, or duplicate Record IDs. Nothing was changed.');
  }

  const beforeCounts = await pool.request().query(
    'SELECT ' +
    '(SELECT COUNT_BIG(*) FROM ' + activeTable + ') AS actualCount, ' +
    '(SELECT COUNT_BIG(*) FROM ' + testBackupTable + ') AS testCount'
  );
  const counts = beforeCounts.recordset[0];
  const transaction = new sql.Transaction(pool);
  await transaction.begin(sql.ISOLATION_LEVEL.SERIALIZABLE);

  try {
    await new sql.Request(transaction).query(
      "EXEC sys.sp_rename N'" + activeTable + "', N'TeaFarmer_Records_Actual_Backup', N'OBJECT';\n" +
      "EXEC sys.sp_rename N'" + testBackupTable + "', N'TeaFarmer_Records', N'OBJECT';"
    );

    const restoredCount = await new sql.Request(transaction).query(
      'SELECT COUNT_BIG(*) AS [recordCount] FROM ' + activeTable
    );
    if (Number(restoredCount.recordset[0].recordCount) !== Number(counts.testCount)) {
      throw new Error('The restored test table count changed during the swap.');
    }

    await transaction.commit();
    console.log('Restored the original test table with ' + counts.testCount + ' records and ' + testSchema.columnCount + ' fields.');
    console.log('The actual baseline table is retained as ' + actualBackupTable + '.');
    console.log(Number(testSchema.identityColumn) === 1
      ? 'Record IDs are generated by the table identity.'
      : 'Record IDs are generated by the application from the next available value.');
    console.log('The backend selects its schema from the active table when it starts.');
  } catch (error) {
    try { await transaction.rollback(); } catch { /* transaction may already be closed */ }
    throw error;
  }
}

main().catch(error => {
  console.error('Test-table restore failed:', error.message);
  process.exitCode = 1;
});
